-- Change this table name for every new invite.
-- Keep it in sync with INVITE_TABLE in .env.local and in Vercel.

create table if not exists public.partecipanti_template_2 (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  partecipa boolean not null default true,
  guests integer not null default 1,
  food_preferences text not null default '',
  message text not null default ''
);

alter table public.partecipanti_template_2
  add column if not exists food_preferences text not null default '';

alter table public.partecipanti_template_2 enable row level security;

